#!/usr/bin/env node
/**
 * Inject Cloudflare Web Analytics beacon into all site HTML.
 * Idempotent: skips files already containing 'cloudflareinsights'.
 * Excludes: operator/admin dashboard pages.
 * Usage: node scripts/inject-cf-analytics.js
 */
const fs = require('fs');
const path = require('path');

const SNIPPET = `<!-- Cloudflare Web Analytics -->
<script type='module' src='https://static.cloudflareinsights.com/beacon.min.js' data-cf-beacon='{"token": "156afa3b1ed1486cb0fc62708b1802ce"}'></script>
<!-- End Cloudflare Web Analytics -->`;

const EXCLUDE = new Set(['ab-dashboard.html', 'instructor-dashboard.html', 'admin.html']);

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.name.endsWith('.html') && !EXCLUDE.has(e.name)) out.push(p);
  }
  return out;
}

const files = [];
walk('landing', files);
walk('content', files);
walk('public', files); // hand-maintained / stale files not regenerated by build
// hand-maintained page not regenerated by build
if (fs.existsSync('public/case-engine.html')) files.push('public/case-engine.html');

let injected = 0, skipped = 0;
for (const f of files) {
  let html = fs.readFileSync(f, 'utf8');
  if (html.includes('cloudflareinsights')) { skipped++; continue; }
  if (!/<\/head>/i.test(html)) { console.log(`SKIP (no </head>): ${f}`); skipped++; continue; }
  html = html.replace(/<\/head>/i, `${SNIPPET}\n</head>`);
  fs.writeFileSync(f, html);
  injected++;
}
console.log(`injected: ${injected} | already-present/skipped: ${skipped}`);
